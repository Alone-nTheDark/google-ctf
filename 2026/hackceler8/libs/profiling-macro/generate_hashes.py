from pathlib import Path
import re


def fnv1a(name):
  hash_val = 2166136261
  for char in name:
    hash_val ^= ord(char)
    hash_val = (hash_val * 16777619) & 0xFFFFFFFF
  return hash_val


def generate_map(root_dirs, output_file):
  # This regex looks for #[profile], allows for other attributes/whitespace,
  # and then captures the function name.
  profile_re = re.compile(r"#\[profile(?:\((.*?)\))?\].*?fn\s+(\w+)", re.DOTALL)
  trace_re = re.compile(r"trace!\(\"([^\"]*?)\"\)", re.DOTALL)

  # Similar structure, but separate since one is used on 0xFFFF00 and the other on 0xFFFF02
  found_mappings = {}
  found_messages = {}

  for root_dir in root_dirs:
      # Recursively find all .rs files
      for rs_file in Path(root_dir).rglob("*.rs"):
        # Skip the 'target' directory if it exists to save time
        if "target" in rs_file.parts:
          continue

        with open(rs_file, "r", encoding="utf-8") as f:
          content = f.read()
          # Check for profile tags
          matches = profile_re.findall(content)
          for struct_name, fn_name in matches:
            if struct_name:
              name = f"{struct_name.strip()}::{fn_name}"
            else:
              name = fn_name
            fn_id = fnv1a(name) & 0x7FFF
            if fn_id in found_mappings:
                print(f"Warning: Collision detected between {name} and {found_mappings[fn_id]}")
                continue
            found_mappings[fn_id] = name

          # Check for trace tags
          matches = trace_re.findall(content)
          for msg in matches:
            fn_id = fnv1a(msg)
            fn_id = (fn_id >> 16) ^ (fn_id & 0xFFFF)
            if fn_id in found_messages and found_messages[fn_id] != msg:
                print(f"Warning: Collision detected between {msg} and {found_messages[fn_id]}")
                continue
            found_messages[fn_id] = msg

  # Write the Lua file
  with open(output_file, "w", encoding="utf-8") as f:
    f.write("-- Generated by generate_hashes.py - DO NOT EDIT\n")
    f.write("local function_names = {\n")
    # Sort by ID for a cleaner looking file
    for fn_id in sorted(found_mappings.keys()):
      f.write(f'    [0x{fn_id:04x}] = "{found_mappings[fn_id]}",\n')
    f.write("}\n\n")
    f.write("local trace_messages = {\n")
    # Sort by ID for a cleaner looking file
    for fn_id in sorted(found_messages.keys()):
      f.write(f'    [0x{fn_id:04x}] = "{found_messages[fn_id]}",\n')
    f.write("}\n\n")
    f.write("return function_names, trace_messages\n")

  print(f"Success: Mapped {len(found_mappings)} functions to {output_file}")


if __name__ == "__main__":
  # Scans the current directory (".") and outputs "lookup.lua"
  generate_map(["game", "libs/megahx8"], "lookup.lua")
